interface ContactMessagesState {
  messages: ContactMessage[]
  updateMessage: (id: string, updates: Partial<ContactMessage>) => void
  resetToDefaults: () => void
}

export const useContactMessagesStore = create<ContactMessagesState>()(
  persist(
    (set) => ({
      messages: MOCK_MESSAGES,
      updateMessage: (id, updates) =>
        set((s) => ({
          messages: s.messages.map((m) =>
            m.id === id ? { ...m, ...updates } : m
          ),
        })),
      resetToDefaults: () => set({ messages: MOCK_MESSAGES }),
    }),
    { name: 'uposa_contact_messages', version: 2 }
  )
)
