interface AnnouncementsState {
  announcements: Announcement[]
  addAnnouncement: (announcement: Omit<Announcement, 'id' | 'createdAt' | 'updatedAt'>) => Announcement
  updateAnnouncement: (id: string, updates: Partial<Announcement>) => void
  deleteAnnouncement: (id: string) => void
  resetToDefaults: () => void
}

export const useAnnouncementsStore = create<AnnouncementsState>()(
  persist(
    (set) => ({
      announcements: MOCK_ANNOUNCEMENTS,
      addAnnouncement: (announcement) => {
        const newAnnouncement: Announcement = {
          ...announcement,
          id: `ann-${Date.now()}`,
          createdAt: new Date().toISOString(),
          updatedAt: new Date().toISOString(),
        }
        set((s) => ({ announcements: [newAnnouncement, ...s.announcements] }))
        return newAnnouncement
      },
      updateAnnouncement: (id, updates) =>
        set((s) => ({
          announcements: s.announcements.map((a) =>
            a.id === id ? { ...a, ...updates, updatedAt: new Date().toISOString() } : a
          ),
        })),
      deleteAnnouncement: (id) =>
        set((s) => ({ announcements: s.announcements.filter((a) => a.id !== id) })),
      resetToDefaults: () => set({ announcements: MOCK_ANNOUNCEMENTS }),
    }),
    { name: 'uposa_announcements', version: 2 }
  )
)
