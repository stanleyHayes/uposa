interface ExecutivesState {
  executives: Executive[]
  addExecutive: (executive: Omit<Executive, 'id' | 'createdAt' | 'updatedAt'>) => Executive
  updateExecutive: (id: string, updates: Partial<Executive>) => void
  deleteExecutive: (id: string) => void
  resetToDefaults: () => void
}

export const useExecutivesStore = create<ExecutivesState>()(
  persist(
    (set) => ({
      executives: MOCK_EXECUTIVES,
      addExecutive: (executive) => {
        const newExecutive: Executive = {
          ...executive,
          id: `exec-${Date.now()}`,
          createdAt: new Date().toISOString(),
          updatedAt: new Date().toISOString(),
        }
        set((s) => ({ executives: [newExecutive, ...s.executives] }))
        return newExecutive
      },
      updateExecutive: (id, updates) =>
        set((s) => ({
          executives: s.executives.map((e) =>
            e.id === id ? { ...e, ...updates, updatedAt: new Date().toISOString() } : e
          ),
        })),
      deleteExecutive: (id) =>
        set((s) => ({ executives: s.executives.filter((e) => e.id !== id) })),
      resetToDefaults: () => set({ executives: MOCK_EXECUTIVES }),
    }),
    { name: 'uposa_executives', version: 2 }
  )
)
